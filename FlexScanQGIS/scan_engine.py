"""Flexible spatial scan implementation following Tango & Takahashi (2005).

Candidate zones are connected subsets of each seed's K-nearest-region window.
The code is an independent implementation; numerical equivalence with
FleXScan/rflexscan must be established before research results are treated as
equivalent.
"""
from array import array
import math
import random

try:
    import numpy as np
except ImportError:  # QGIS distributions normally bundle NumPy
    np = None


def expected_from_population(observed, population):
    """Expected counts under a common rate and population-at-risk offsets."""
    if len(observed) != len(population):
        raise ValueError("症例数とリスク人口の長さが一致しません")
    if any(not math.isfinite(float(x)) or float(x) < 0 for x in observed):
        raise ValueError("症例数は0以上の有限値である必要があります")
    if any(not math.isfinite(float(x)) or float(x) < 0 for x in population):
        raise ValueError("リスク人口は0以上の有限値である必要があります")
    total_cases = sum(float(x) for x in observed)
    total_population = sum(float(x) for x in population)
    if total_cases <= 0:
        raise ValueError("全地域の症例数合計が0です")
    if total_population <= 0:
        raise ValueError("リスク人口の合計が0です")
    if any(float(cases) > 0 and float(pop) == 0
           for cases, pop in zip(observed, population)):
        raise ValueError("リスク人口が0の地域に症例数があります。人口フィールドを確認してください。")
    return [total_cases * float(pop) / total_population for pop in population]


def _members(mask):
    """Yield region indices from a Python integer bit mask."""
    while mask:
        bit = mask & -mask
        yield bit.bit_length() - 1
        mask ^= bit


def connected_candidates(adjacency, nearest_neighbors, max_size,
                         cancel=None, max_candidates=2_000_000,
                         status=None):
    """Yield each valid connected candidate once, without a global seen set.

    For each seed, candidates are restricted to that seed and its K-1 nearest
    regions. Overlapping candidates generated by multiple seeds are emitted
    only from the lowest-index seed whose K-neighbour window contains the full
    candidate. This preserves the union of candidate windows while avoiding a
    potentially very large global duplicate set.
    """
    n = len(adjacency)
    if len(nearest_neighbors) != n:
        raise ValueError("近傍リストと隣接データの長さが一致しません")
    windows = []
    for root, nearest in enumerate(nearest_neighbors):
        window = set(nearest[:max_size - 1])
        window.add(root)
        windows.append(window)

    count = 0
    interval = max(1, n // 20)
    for root, allowed in enumerate(windows):
        if status and (root == 0 or (root + 1) % interval == 0 or root == n - 1):
            status(f"近傍候補を探索中: 起点地域 {root + 1}/{n}")
        local_seen = set()
        frontier = [frozenset((root,))]
        while frontier:
            current = frontier.pop()
            if current in local_seen:
                continue
            local_seen.add(current)

            # A candidate is valid for this seed iff its complete member set
            # is inside this seed's K-nearest window. Emit it only once.
            canonical_root = root
            for member in sorted(current):
                if member >= canonical_root:
                    break
                if current.issubset(windows[member]):
                    canonical_root = member
                    break
            if canonical_root == root:
                count += 1
                if count > max_candidates:
                    raise RuntimeError(
                        f"候補領域数が上限{max_candidates:,}を超えました。"
                        "最大クラスター地域数Kを下げるか、解析範囲を分割してください。"
                    )
                yield tuple(sorted(current))

            if len(current) >= max_size:
                continue
            boundary = set()
            for member in current:
                boundary.update(adjacency[member])
            boundary.intersection_update(allowed)
            boundary.difference_update(current)
            for member in boundary:
                nxt = current | frozenset((member,))
                if nxt not in local_seen:
                    frontier.append(nxt)
            if cancel and cancel():
                return


def _nearest_from_coordinates(coordinates, max_size):
    """Find nearest regions; prefer SciPy's spatial tree when available."""
    n = len(coordinates)
    if max_size <= 1:
        return [[] for _ in range(n)]
    try:
        import numpy as np_local
        from scipy.spatial import cKDTree
        points = np_local.asarray(coordinates, dtype=float)
        tree = cKDTree(points)
        k = min(n, max_size + 1)
        distances, indices = tree.query(points, k=k)
        if k == 1:
            indices = indices.reshape(n, 1)
            distances = distances.reshape(n, 1)
        output = []
        for root in range(n):
            candidates = set(int(v) for v in np_local.atleast_1d(indices[root]) if int(v) != root)
            ranked = sorted(candidates,
                            key=lambda i: ((coordinates[i][0] - coordinates[root][0]) ** 2 +
                                           (coordinates[i][1] - coordinates[root][1]) ** 2, i))
            if len(ranked) < max_size - 1:
                ranked = sorted((i for i in range(n) if i != root),
                                key=lambda i: ((coordinates[i][0] - coordinates[root][0]) ** 2 +
                                               (coordinates[i][1] - coordinates[root][1]) ** 2, i))
            output.append(ranked[:max_size - 1])
        return output
    except ImportError:
        return [sorted((i for i in range(n) if i != root),
                       key=lambda i: ((coordinates[i][0] - coordinates[root][0]) ** 2 +
                                      (coordinates[i][1] - coordinates[root][1]) ** 2, i))[:max_size - 1]
                for root in range(n)]


def _score_batch(counts, indices, expected_padded, total_cases, total_expected,
                 direction):
    """Vectorized Poisson LLR for multiple simulations and candidate zones."""
    zone_cases = counts[:, indices].sum(axis=2, dtype=np.float64)
    zone_expected = expected_padded[indices].sum(axis=1, dtype=np.float64)
    outside_cases = total_cases - zone_cases
    outside_expected = total_expected - zone_expected
    valid = (zone_expected > 0) & (outside_expected > 0)
    inside_rate = np.divide(zone_cases, zone_expected,
                            out=np.zeros_like(zone_cases), where=zone_expected > 0)
    outside_rate = np.divide(outside_cases, outside_expected,
                             out=np.zeros_like(outside_cases), where=outside_expected > 0)
    if direction == "HOT":
        direction_ok = inside_rate > outside_rate
    elif direction == "COLD":
        direction_ok = inside_rate < outside_rate
    else:
        direction_ok = inside_rate != outside_rate
    terms = np.zeros_like(zone_cases, dtype=np.float64)
    inside_positive = zone_cases > 0
    outside_positive = outside_cases > 0
    with np.errstate(divide="ignore", invalid="ignore"):
        terms += np.where(inside_positive,
                          zone_cases * np.log(np.divide(zone_cases, zone_expected,
                              out=np.ones_like(zone_cases), where=zone_expected > 0)), 0.0)
        terms += np.where(outside_positive,
                          outside_cases * np.log(np.divide(outside_cases, outside_expected,
                              out=np.ones_like(outside_cases), where=outside_expected > 0)), 0.0)
        base = total_cases * math.log(total_cases / total_expected)
    values = np.maximum(0.0, terms - base)
    values[~direction_ok] = 0.0
    values[:, ~valid] = 0.0
    return values, zone_cases, zone_expected, outside_rate


def scan(observed, expected, adjacency, coordinates, max_size=15, simulations=999,
         direction="HOT", seed=12345, progress=None, status=None, cancel=None,
         nearest_neighbors=None, max_candidates=2_000_000,
         max_secondary_clusters=0):
    if np is None:
        raise RuntimeError("大規模候補領域の評価にはQGIS Python環境のNumPyが必要です")
    n = len(observed)
    if n != len(expected) or n != len(adjacency) or n != len(coordinates):
        raise ValueError("入力配列の長さが一致しません")
    if any(not math.isfinite(float(x)) or float(x) < 0 for x in observed):
        raise ValueError("症例数は0以上の有限値で指定してください")
    if any(not math.isfinite(float(x)) or float(x) < 0 for x in expected):
        raise ValueError("期待数は0以上の有限値で指定してください")
    if not 1 <= max_size <= n:
        raise ValueError("最大クラスターサイズは1から地域数までです")
    if simulations < 0:
        raise ValueError("シミュレーション回数は0以上にしてください")
    if max_secondary_clusters < 0:
        raise ValueError("二次クラスター数は0以上にしてください")
    if direction not in ("HOT", "COLD", "BOTH"):
        raise ValueError("検出方向が不正です")
    for i, neighbors in enumerate(adjacency):
        if i in neighbors or any(j < 0 or j >= n for j in neighbors):
            raise ValueError("隣接行列に自己参照または範囲外IDがあります")
        if any(i not in adjacency[j] for j in neighbors):
            raise ValueError("隣接関係が対称ではありません")
    if any(len(c) != 2 or not all(math.isfinite(float(v)) for v in c)
           for c in coordinates):
        raise ValueError("重心座標に欠損または無限値があります")
    if nearest_neighbors is None:
        if status:
            status("重心距離から近傍地域を準備中")
        nearest_neighbors = _nearest_from_coordinates(coordinates, max_size)

    # Store each candidate as a fixed-width packed int array (0 is padding,
    # region indexes are shifted to 1..n). This avoids millions of Python sets.
    memory_safe_limit = max(1, 60_000_000 // max_size)
    effective_limit = min(max_candidates, memory_safe_limit)
    if status and effective_limit < max_candidates:
        status(f"K={max_size}のため候補上限をメモリ保護値{effective_limit:,}に調整")
    max_candidates = effective_limit
    candidate_data = array("i")
    candidate_count = 0
    if status:
        status(f"候補領域の生成を開始（上限{max_candidates:,}候補）")
    for zone in connected_candidates(adjacency, nearest_neighbors, max_size,
                                     cancel=cancel, max_candidates=max_candidates,
                                     status=status):
        candidate_data.extend(member + 1 for member in zone)
        candidate_data.extend([0] * (max_size - len(zone)))
        candidate_count += 1
    if cancel and cancel():
        raise InterruptedError("解析をキャンセルしました")
    if candidate_count == 0:
        raise ValueError("解析候補領域を生成できませんでした")
    if status:
        status(f"候補領域の生成完了: {candidate_count:,}候補")

    if candidate_data.itemsize != 4:
        raise RuntimeError("候補領域配列の整数幅に対応できません")
    candidate_matrix = np.frombuffer(candidate_data, dtype=np.int32).reshape(candidate_count, max_size)
    expected_padded = np.zeros(n + 1, dtype=np.float64)
    expected_array = np.asarray(expected, dtype=np.float64)
    observed_array = np.asarray(observed, dtype=np.int64)
    expected_padded[1:] = expected_array
    observed_padded = np.zeros(n + 1, dtype=np.int64)
    observed_padded[1:] = observed_array
    total_cases = int(observed_array.sum())
    total_expected = float(expected_array.sum())
    if total_cases <= 0 or total_expected <= 0:
        raise ValueError("症例数または期待数の合計が0です")
    if simulations and abs(total_cases - float(observed_array.sum())) > 1e-8:
        raise ValueError("モンテカルロ検定には整数の症例数が必要です")

    observed_scores = np.zeros(candidate_count, dtype=np.float64)
    candidate_batch = 4096
    if status:
        status("観測データの候補クラスター統計量を計算中")
    for start in range(0, candidate_count, candidate_batch):
        end = min(candidate_count, start + candidate_batch)
        indices = candidate_matrix[start:end]
        values, _, _, _ = _score_batch(
            observed_padded[None, :], indices, expected_padded,
            total_cases, total_expected, direction)
        observed_scores[start:end] = values[0]
        if status and (end == candidate_count or end % (candidate_batch * 20) == 0):
            status(f"観測統計量を評価中: {end:,}/{candidate_count:,}候補")

    best_index = int(np.argmax(observed_scores))
    best_value = float(observed_scores[best_index])
    if status:
        status(f"観測データの評価完了: LLR={best_value:.8g}")
    simulated_maxima = []
    if simulations:
        if abs(total_cases - sum(float(x) for x in observed)) > 1e-8:
            raise ValueError("モンテカルロ検定には整数の症例数が必要です")
        weights = expected_array / total_expected
        cumulative = np.cumsum(weights).tolist()
        rng = random.Random(seed)
        simulation_batch = 16
        if status:
            status(f"帰無分布を生成中: {simulations:,}回、乱数種={seed}")
        for sim_start in range(0, simulations, simulation_batch):
            sim_end = min(simulations, sim_start + simulation_batch)
            batch_size = sim_end - sim_start
            sim_counts = np.zeros((batch_size, n + 1), dtype=np.int32)
            for row in range(batch_size):
                for _ in range(total_cases):
                    u = rng.random()
                    lo, hi = 0, n
                    while lo < hi:
                        mid = (lo + hi) // 2
                        if u <= cumulative[mid]:
                            hi = mid
                        else:
                            lo = mid + 1
                    sim_counts[row, min(lo, n - 1) + 1] += 1
            sim_best = np.zeros(batch_size, dtype=np.float64)
            for start in range(0, candidate_count, candidate_batch):
                end = min(candidate_count, start + candidate_batch)
                values, _, _, _ = _score_batch(
                    sim_counts, candidate_matrix[start:end], expected_padded,
                    total_cases, total_expected, direction)
                sim_best = np.maximum(sim_best, values.max(axis=1))
                if cancel and cancel():
                    raise InterruptedError("解析をキャンセルしました")
            simulated_maxima.extend(float(v) for v in sim_best)
            completed = sim_end
            if progress:
                progress(completed, simulations)
            if status and (completed == simulations or
                           completed % max(simulation_batch, simulations // 20) == 0):
                status(f"モンテカルロ検定: {completed:,}/{simulations:,}回完了")
            if cancel and cancel():
                raise InterruptedError("解析をキャンセルしました")
    sorted_simulated_maxima = (np.sort(np.asarray(simulated_maxima, dtype=np.float64))
                               if simulated_maxima else None)

    def monte_carlo_pvalue(statistic):
        if sorted_simulated_maxima is None:
            return None
        exceed = len(sorted_simulated_maxima) - int(np.searchsorted(
            sorted_simulated_maxima, statistic - 1e-12, side="left"))
        return (exceed + 1) / (simulations + 1)

    primary_p = monte_carlo_pvalue(best_value)
    if status and simulations:
        primary_exceed = int(round(primary_p * (simulations + 1) - 1))
        status(f"一次クラスター検定完了: 超過数={primary_exceed:,}, p値={primary_p:.8g}")

    # The rflexscan secondary-cluster procedure repeatedly selects the
    # highest-scoring candidate that does not overlap previously selected
    # clusters. Each selected cluster is tested against the same simulated
    # distribution of maximum scan statistics as if it were primary.
    cluster_order = np.argsort(-observed_scores, kind="stable")
    selected_clusters = []
    occupied = set()
    secondary_count = 0
    for candidate_index in cluster_order:
        if not simulations and max_secondary_clusters == 0 and selected_clusters:
            break
        if len(selected_clusters) and max_secondary_clusters > 0 and \
                secondary_count >= max_secondary_clusters:
            break
        row = candidate_matrix[int(candidate_index)]
        members = [int(v) - 1 for v in row if v > 0]
        member_set = set(members)
        if occupied.intersection(member_set):
            continue
        statistic = float(observed_scores[int(candidate_index)])
        p_value = monte_carlo_pvalue(statistic)
        if selected_clusters and p_value is not None and p_value >= 1.0:
            if status:
                status("二次クラスター探索を終了: 次候補のp値が1")
            break
        zone_cases = float(sum(float(observed[i]) for i in members))
        zone_expected = float(sum(float(expected[i]) for i in members))
        outside_expected = total_expected - zone_expected
        inside_rate = zone_cases / zone_expected if zone_expected else 0.0
        outside_cases = total_cases - zone_cases
        outside_rate = outside_cases / outside_expected if outside_expected else 0.0
        relative_risk = (inside_rate / outside_rate if outside_rate else
                         (math.inf if inside_rate else 1.0))
        cluster = {
            "rank": len(selected_clusters) + 1,
            "members": members,
            "statistic": statistic,
            "relative_risk": relative_risk,
            "cases": zone_cases,
            "expected": zone_expected,
            "p_value": p_value,
            "secondary_limit": max_secondary_clusters,
        }
        selected_clusters.append(cluster)
        occupied.update(member_set)
        if cluster["rank"] > 1:
            secondary_count += 1
        if status:
            ptext = "未算出" if p_value is None else f"{p_value:.8g}"
            status(f"クラスター順位{cluster['rank']}: 地域数={len(members)}, "
                   f"LLR={statistic:.8g}, p値={ptext}")
        if cancel and cancel():
            raise InterruptedError("解析をキャンセルしました")

    if not selected_clusters:
        raise RuntimeError("一次クラスターを選択できませんでした")
    primary = selected_clusters[0]
    if status:
        status(f"クラスター探索完了: {len(selected_clusters)}件 "
               f"（一次1件、二次{len(selected_clusters) - 1}件）")
    return {"statistic": primary["statistic"], "members": primary["members"],
            "relative_risk": primary["relative_risk"], "cases": primary["cases"],
            "p_value": primary["p_value"], "clusters": selected_clusters,
            "candidate_count": candidate_count, "simulations": simulations,
            "seed": seed, "candidate_limit": max_candidates,
            "direction": direction,
            "max_secondary_clusters": max_secondary_clusters}
